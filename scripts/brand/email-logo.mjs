// Build the logo every e-mail carries.
//
// Reads:  docs/brand/vidalo-logo.svg   mark + wordmark, the wordmark outlined from Plus Jakarta
//                                      Sans ExtraBold the way components/Logo.tsx sets it
// Writes: packages/core/src/reporter/logo.ts   the logo as a base64 PNG, for an inline (cid:) image
//         apps/web/public/mail/vidalo-logo.png the same PNG, for the Supabase sign-in mail
//                                              (docs/brand/supabase-magic-link.html), which can
//                                              only point at a hosted image
//
// Why inline, as on Sitty: a cid: image travels inside the message, so it shows in clients that
// block remote images (Outlook does) and no request leaves the reader's client. The Worker has no
// filesystem, so the bytes are compiled in as a string.
//
// Run: node scripts/brand/email-logo.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
// sharp is not a workspace dependency; Next brings it along.
const fromWeb = createRequire(join(ROOT, "apps/web/package.json"));
const sharp = createRequire(fromWeb.resolve("next/package.json"))("sharp");

// Shown at 120px wide in the mail; 2x for high-density screens.
const DISPLAY_WIDTH = 120;

const svg = readFileSync(join(ROOT, "docs/brand/vidalo-logo.svg"));
const png = await sharp(svg, { density: 300 }).resize({ width: DISPLAY_WIDTH * 2 }).png({ compressionLevel: 9 }).toBuffer();
const { width, height } = await sharp(png).metadata();
const displayHeight = Math.round((height / width) * DISPLAY_WIDTH);

// The logo sits on white: a transparent PNG is right there, and a blank one is the failure.
const alpha = (await sharp(png).stats()).channels[3];
if (!alpha || alpha.max === 0) {
  console.error("FAIL the e-mail logo rendered with no visible pixels");
  process.exit(1);
}

writeFileSync(
  join(ROOT, "packages/core/src/reporter/logo.ts"),
  `// Generated by scripts/brand/email-logo.mjs from docs/brand/vidalo-logo.svg. Do not hand-edit.

export const LOGO = {
  contentId: "vidalo-logo",
  filename: "vidalo.png",
  width: ${DISPLAY_WIDTH},
  height: ${displayHeight},
  base64: "${png.toString("base64")}",
} as const;
`,
);
mkdirSync(join(ROOT, "apps/web/public/mail"), { recursive: true });
writeFileSync(join(ROOT, "apps/web/public/mail/vidalo-logo.png"), png);
console.log(`packages/core/src/reporter/logo.ts, apps/web/public/mail/vidalo-logo.png (${width}x${height}, ${png.length} bytes)`);
