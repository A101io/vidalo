// Check profiles.json: every platform has every language and fits the platform's limit.
// Writes one ready-to-paste file per language: docs/brand/social/<lang>.md
//
// Run: node docs/brand/social/check.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const { link, platforms } = JSON.parse(readFileSync(join(DIR, "profiles.json"), "utf8"));
const langs = Object.keys(link);

let failed = false;
for (const lang of langs) {
  const out = [`# Vidalo social profiles (${lang})`, "", "Generated by check.mjs from profiles.json. Edit the JSON, not this file.", "", `Avatar: avatar/vidalo-avatar-blue.png`, "", `Link: ${link[lang]}`, ""];
  for (const [name, p] of Object.entries(platforms)) {
    const text = p[lang];
    if (!text) {
      console.error(`FAIL ${name}: no "${lang}" text`);
      failed = true;
      continue;
    }
    const len = [...text].length;
    const ok = len <= p.limit;
    if (!ok) failed = true;
    console.log(`${ok ? "ok  " : "FAIL"} ${lang} ${name} ${len}/${p.limit}`);
    out.push(`## ${name} — ${p.field} (${len}/${p.limit})`, "", "```", text, "```", "");
  }
  writeFileSync(join(DIR, `${lang}.md`), out.join("\n"));
}
process.exit(failed ? 1 : 0);
