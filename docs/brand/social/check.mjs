// Check profiles.json: every field has every language and fits the platform's limit
// (characters for text, items for a list). Writes one ready-to-paste file per language:
// docs/brand/social/<lang>.md
//
// Run: node docs/brand/social/check.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const { link, platforms, banner } = JSON.parse(readFileSync(join(DIR, "profiles.json"), "utf8"));
const langs = Object.keys(link);

let failed = false;
for (const lang of langs) {
  const out = [
    `# Vidalo social profiles (${lang})`,
    "",
    "Generated by check.mjs from profiles.json. Edit the JSON, not this file.",
    "",
    "Avatar: `avatar/vidalo-avatar-blue.png` · Banners: `banner/" + lang + "/`",
    "",
    `Link: ${link[lang]}`,
    "",
  ];
  for (const [platform, fields] of Object.entries(platforms)) {
    out.push(`## ${platform}`, "");
    for (const [field, f] of Object.entries(fields)) {
      const value = f[lang];
      if (!value) {
        console.error(`FAIL ${lang} ${platform} ${field}: missing`);
        failed = true;
        continue;
      }
      const list = Array.isArray(value);
      const len = list ? value.length : [...value].length;
      const ok = len <= f.limit;
      if (!ok) failed = true;
      console.log(`${ok ? "ok  " : "FAIL"} ${lang} ${platform} ${field} ${len}/${f.limit}`);
      out.push(`### ${field} (${len}/${f.limit}${list ? " items" : ""})`, "");
      for (const text of list ? value : [value]) out.push("```", text, "```", "");
    }
  }
  if (!banner.alt[lang]) failed = true;
  out.push("## Banner alt text", "", "```", banner.alt[lang] ?? "", "```", "");
  writeFileSync(join(DIR, `${lang}.md`), out.join("\n"));
}
process.exit(failed ? 1 : 0);
